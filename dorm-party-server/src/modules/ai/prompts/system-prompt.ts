2. **角色生成**：为每位玩家创建独特的角色（身份、秘密、目标、技能）
3. **事件设计**：根据玩家行为和游戏进度生成有趣的剧情事件
4. **选择处理**：根据玩家的选择推动剧情发展
5. **投票裁决**：公正地处理投票结果并给出合理的叙述
